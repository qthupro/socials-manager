/**
 * Bundles convex/ into the `start_push` request the app sends to each user's own Convex
 * deployment (src/features/realtime/backend/deploy.ts), so users deploy with only their
 * prod deploy key — no Node / Convex CLI on their machine.
 *
 * Runs `convex deploy --write-push-request` against a placeholder deployment: the CLI
 * bundles and writes the request, then stops before any network call.
 *
 * Writes push-request.json (the request, minus the admin key) and version.ts (its hash —
 * when it changes, the app redeploys users' backends by itself).
 *
 * Usage: pnpm convex:bundle (after editing convex/; the output is committed)
 */
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const outDir = path.join(root, "src/features/realtime/backend");
const tmp = mkdtempSync(path.join(tmpdir(), "convex-bundle-"));

try {
  const result = spawnSync(
    process.execPath,
    [
      path.join(root, "node_modules/convex/bin/main.js"),
      "deploy",
      "--url",
      "https://placeholder.convex.cloud",
      "--admin-key",
      "placeholder",
      "--write-push-request",
      path.join(tmp, "push"),
      "--push-all-modules",
      "--codegen",
      "disable",
      "--typecheck",
      "disable",
      "--yes",
    ],
    { cwd: root, stdio: "inherit" },
  );
  if (result.status !== 0) process.exit(result.status ?? 1);

  const request = JSON.parse(readFileSync(path.join(tmp, "push.json"), "utf8"));
  delete request.adminKey;
  const json = JSON.stringify(request);
  const version = createHash("sha256").update(json).digest("hex").slice(0, 16);
  writeFileSync(path.join(outDir, "push-request.json"), json + "\n");
  writeFileSync(
    path.join(outDir, "version.ts"),
    `// Generated by scripts/build-convex.mjs — do not edit.\nexport const BACKEND_VERSION = "${version}";\n`,
  );
  console.log(`Wrote ${path.relative(root, outDir)} (backend version ${version})`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
